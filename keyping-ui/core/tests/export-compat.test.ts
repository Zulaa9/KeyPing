// Compatibilidad del archivo de exportación entre el escritorio y el móvil (núcleo + Web Crypto).
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'fs';
import * as path from 'path';
import { KeypingService } from '../keyping-service';
import { webCrypto } from '../web-crypto';
import { hmacSha256Hex } from '../sha256';
import { fromHex } from '../bytes';
import { FIXTURES, FakeNative, MemoryStore, withDesktopVault } from './helpers';

const expected = JSON.parse(readFileSync(path.join(FIXTURES, 'desktop-expected.json'), 'utf8'));
const PASSWORD: string = expected.exportPassword;
const fixture = (name: string) => readFileSync(path.join(FIXTURES, name), 'utf8');

const FIELDS = ['id', 'createdAt', 'updatedAt', 'twoFactorEnabled', 'length', 'classMask', 'secret', 'normalized', 'label',
  'active', 'previousId', 'loginUrl', 'passwordChangeUrl', 'username', 'email', 'folder', 'iconName', 'iconSource',
  'detectedService'];

/** Compara campo a campo (todo salvo `hash`, que depende de la clave HMAC de cada bóveda). */
function assertSameEntries(actual: any[], wanted: any[], ctx: string): void {
  assert.equal(actual.length, wanted.length, `${ctx}: número de entradas`);
  const byId = new Map(actual.map(e => [e.id, e]));
  for (const w of wanted) {
    const a = byId.get(w.id);
    assert.ok(a, `${ctx}: falta la entrada ${w.id}`);
    for (const f of FIELDS) assert.deepEqual(a[f], w[f], `${ctx}: ${w.id}.${f}`);
  }
}

async function mobile(): Promise<{ svc: KeypingService; store: MemoryStore }> {
  const store = new MemoryStore();
  const svc = new KeypingService('android', store, webCrypto, new FakeNative());
  assert.deepEqual(await svc.authSetup('Maestra-Movil-123'), { ok: true });
  return { svc, store };
}

async function mobileHashKey(store: MemoryStore): Promise<Uint8Array> {
  return fromHex(JSON.parse((await store.read('kp-hash.key'))!).key);
}

test('fixtures were generated by the desktop export (format and parameters)', () => {
  for (const name of ['desktop-full-history.kpenc', 'desktop-current-only.kpenc']) {
    const p = JSON.parse(fixture(name));
    assert.deepEqual(Object.keys(p), ['format', 'enc', 'iterations', 'salt', 'data']);
    assert.equal(p.format, 'keyping-export-v2');
    assert.equal(p.enc, 'master');
    assert.equal(p.iterations, 600000);
    assert.equal(Buffer.from(p.salt, 'base64').length, 16);
  }
  assert.ok(expected.fullHistory.some((e: any) => e.previousId), 'el fixture incluye historial');
  assert.ok(expected.fullHistory.some((e: any) => /[^\x00-\x7f]/.test(e.secret)), 'incluye secretos no ASCII');
});

for (const [name, key] of [['desktop-full-history.kpenc', 'fullHistory'], ['desktop-current-only.kpenc', 'currentOnly']] as const) {
  test(`mobile imports ${name} field by field`, async () => {
    const { svc, store } = await mobile();
    const preview = await svc.parseImport(fixture(name), PASSWORD);
    assert.equal(preview.source, 'master');
    for (const p of preview.entries) assert.ok(!('secret' in p) && !('hash' in p) && !('normalized' in p));
    const result = await svc.importVault('overwrite');
    assert.equal(result.imported, expected[key].filter((e: any) => e.active !== false).length);
    const all = await (svc as any).ops.entries();
    assertSameEntries(all, expected[key], name);
    const hk = await mobileHashKey(store);
    for (const e of all) assert.equal(e.hash, hmacSha256Hex(e.secret, hk), 'hash recalculado con la clave del móvil');
    // Lo que ve la interfaz.
    const list = await svc.listPasswords();
    const gmail = list.find((e: any) => e.detectedService === 'gmail');
    assert.equal(gmail.passwordChangeUrl, 'https://mail.example.com/security/password');
    assert.equal(await svc.getPassword(gmail.id), 'Perro-Verde-2026#');
    if (key === 'fullHistory') {
      const history = await svc.getPasswordHistory(gmail.id);
      assert.equal(history.length, 3);
      assert.deepEqual(history.map((h: any) => h.active), [true, false, false]);
    }
  });
}

test('mobile export imports in the desktop without differences', async () => {
  const { svc } = await mobile();
  await svc.parseImport(fixture('desktop-full-history.kpenc'), PASSWORD);
  await svc.importVault('overwrite');
  const extra = await svc.savePassword('Móvil-Nueva-ü-9', 'Creada en el móvil 📱', 'm.example.com/login', 'https://m.example.com/pw',
    'movil', 'movil@example.com', 'Móvil', true, 'github', 'manual', 'github');
  await svc.updatePassword(extra.id, 'Móvil-Nueva-ü-10');
  const res = await svc.exportVault('master', 'Clave-Exporta-Móvil-ñ', true);
  assert.equal(res.filename.endsWith('.kpenc'), true);
  const fileText = JSON.stringify(res.payload);
  assert.deepEqual(Object.keys(JSON.parse(fileText)), ['format', 'enc', 'iterations', 'salt', 'data']);
  const mobileAll = await (svc as any).ops.entries();

  await withDesktopVault(async d => {
    const parsed = await d.vault.parseImportPayload(fileText, 'Clave-Exporta-Móvil-ñ');
    assert.equal(parsed.source, 'master');
    assertSameEntries(parsed.entries, mobileAll, 'desktop parse');
    await d.vault.overwriteVaultWithEntries(parsed.entries);
    const desk = await d.vault.getVaultEntries();
    assertSameEntries(desk, mobileAll, 'desktop vault');
    const hist = await d.vault.getPasswordHistory(desk.find((e: any) => e.secret === 'Móvil-Nueva-ü-10').id);
    assert.equal(hist.length, 2);
    // Fusión (merge) también desde el archivo del móvil.
    const merged = await d.vault.mergeVaultEntries(parsed.entries);
    assert.equal(merged, mobileAll.filter((e: any) => e.active !== false).length);
  });
});

test('round trip desktop -> mobile -> desktop keeps every field', async () => {
  await withDesktopVault(async d => {
    const parsed = await d.vault.parseImportPayload(fixture('desktop-full-history.kpenc'), PASSWORD);
    await d.vault.overwriteVaultWithEntries(parsed.entries);
    const original = await d.vault.getVaultEntries();
    const exported = JSON.stringify(await d.vault.exportVaultWithPassword('Ida-Vuelta-✓', true));

    const { svc } = await mobile();
    await svc.parseImport(exported, 'Ida-Vuelta-✓');
    await svc.importVault('overwrite');
    const back = JSON.stringify((await svc.exportVault('master', 'Vuelta-✓', true)).payload);

    const again = await d.vault.parseImportPayload(back, 'Vuelta-✓');
    await d.vault.overwriteVaultWithEntries(again.entries);
    assertSameEntries(await d.vault.getVaultEntries(), original, 'ida y vuelta');
  });
});

test('wrong password, truncated, tampered and non-portable files give clear errors', async () => {
  const { svc } = await mobile();
  const good = fixture('desktop-full-history.kpenc');
  await assert.rejects(svc.parseImport(good, 'incorrecta'), /import-wrong-password/);
  const p = JSON.parse(good);
  await assert.rejects(svc.parseImport(good.slice(0, good.length / 2)), /invalid-import-file/);
  await assert.rejects(svc.parseImport(JSON.stringify({ ...p, data: p.data.slice(0, 20) }), PASSWORD), /import-wrong-password/);
  const raw = Buffer.from(p.data, 'base64'); raw[raw.length - 1] ^= 0xff;
  await assert.rejects(svc.parseImport(JSON.stringify({ ...p, data: raw.toString('base64') }), PASSWORD), /import-wrong-password/);
  await assert.rejects(svc.parseImport(JSON.stringify({ ...p, salt: 5 }), PASSWORD), /invalid-import-file/);
  await assert.rejects(svc.parseImport(fixture('desktop-native-v1.keyping')), /import-native-key-mismatch/);
  await assert.rejects(svc.parseImport('{"format":"otro"}'), /invalid-import-file/);
  // Sin contraseña: pide la de exportación sin descifrar nada.
  assert.deepEqual(await svc.parseImport(good), { source: 'master', requiresPassword: true, entries: [] });
  await assert.rejects(svc.importVault('overwrite'), /import-expired/);
});

test('desktop rejects the mobile file with the wrong password and a mobile native export', async () => {
  const { svc } = await mobile();
  await svc.savePassword('Solo-Una-Entrada-1', 'x');
  const master = JSON.stringify((await svc.exportVault('master', 'Correcta-1', true)).payload);
  const native = await svc.exportVault('native', undefined, true);
  await withDesktopVault(async d => {
    await assert.rejects(d.vault.parseImportPayload(master, 'otra'), /import-wrong-password/);
    const nativeFile = JSON.stringify({ format: native.format, enc: native.enc, vault: native.base64 });
    await assert.rejects(d.vault.parseImportPayload(nativeFile), /import-native-key-mismatch/);
  });
});
