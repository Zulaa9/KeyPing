export const DICTS: Record<Lang, Record<MsgKey, string>> = { es: ES, en: EN };
const LANG_KEY = 'kp-mobile-lang';

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'es' || saved === 'en') return saved;
  } catch { /* almacenamiento no disponible */ }
  return (navigator.language || '').toLowerCase().startsWith('es') ? 'es' : 'en';
}

@Injectable({ providedIn: 'root' })
export class I18n {
  readonly lang = signal<Lang>(initialLang());

  constructor() {
    document.documentElement.lang = this.lang();
  }

  setLang(lang: Lang): void {
    this.lang.set(lang);
    document.documentElement.lang = lang;
    try { localStorage.setItem(LANG_KEY, lang); } catch { /* sin persistencia */ }
  }

  t(key: MsgKey | string, params?: Record<string, string | number>): string {
    const dict = DICTS[this.lang()] as Record<string, string>;
    let s = dict[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{{${k}}}`).join(String(v));
    return s;
  }

  date(ts?: number): string {
    if (!ts) return '';
    return new Date(ts).toLocaleDateString(this.lang() === 'es' ? 'es-ES' : 'en-GB', { day: 'numeric', month: 'short', year: 'numeric' });
  }
}
